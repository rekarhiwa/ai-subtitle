  static List<AppFeature> byCategory(FeatureCategory c) =>
      _all.where((f) => f.category == c).toList();

  static List<AppFeature> search(String q) {
    final s = q.trim().toLowerCase();
    if (s.isEmpty) return _all;
    return _all
        .where(
          (f) =>
              f.titleEn.toLowerCase().contains(s) ||
              f.titleKu.contains(q.trim()) ||
              '${f.number}'.contains(s) ||
              f.id.contains(s),
        )
        .toList();
  }

  static AppFeature? byId(String id) {
    for (final f in _all) {
      if (f.id == id) return f;
    }
    return null;
