enum FeatureStatus {
  /// Wired and usable in this app.
  ready,
  /// Partial / preview controls exist.
  partial,
  /// Listed for roadmap; UI entry only.
  planned,
}

class AppFeature {
  const AppFeature({
    required this.id,
    required this.number,
    required this.titleKu,
    required this.titleEn,
    required this.category,
    required this.icon,
    required this.status,
    this.actionId,
  });

  final String id;
  final int number;
  final String titleKu;
  final String titleEn;
  final FeatureCategory category;
  final IconData icon;
  final FeatureStatus status;

  /// Maps to [FeatureActions] handler key.
  final String? actionId;
}

